import numpy as np

arr1 = np.random.randint(0, 101, 10)
print("Завдання 1")
print("Масив:", arr1)
print("Мінімальне:", np.min(arr1))
print("Максимальне:", np.max(arr1))
print("Середнє:", np.mean(arr1))
arr1_sorted = np.sort(arr1)
print("Масив після сортування:", arr1_sorted)
print("Масив до сортування:", arr1)
print()

arr2 = np.random.randint(1, 51, (4, 4))
print("Завдання 2")
print(arr2)
print("Суми за рядками:", np.sum(arr2, axis=1))
print("Суми за стовпцями:", np.sum(arr2, axis=0))
print("Середнє значення масиву:", np.mean(arr2))
print()

arr3 = np.arange(15).reshape(3, 5)
print("Завдання 3")
print("Початковий масив:")
print(arr3)
print("Транспонований масив:")
print(arr3.T)
print("Масив після reshape:")
print(arr3.reshape(5, 3))
print()

arr4 = np.random.random((10, 10))
print("Завдання 4")
print(arr4)
min_value = np.min(arr4)
max_value = np.max(arr4)
min_index = np.unravel_index(np.argmin(arr4), arr4.shape)
max_index = np.unravel_index(np.argmax(arr4), arr4.shape)
print("Мінімальне значення:", min_value)
print("Індекс мінімального значення:", min_index)
print("Максимальне значення:", max_value)
print("Індекс максимального значення:", max_index)
print()

arr5 = np.random.randint(-10, 11, 15)
print("Завдання 5")
print("Масив:", arr5)
print("Додатні елементи:", arr5[arr5 > 0])
print("Парні елементи:", arr5[arr5 % 2 == 0])
print()

arr6_a = np.arange(1, 6)
arr6_b = np.arange(6, 11)
print("Завдання 6")
print("Перший масив:", arr6_a)
print("Другий масив:", arr6_b)
print("concatenate:", np.concatenate((arr6_a, arr6_b)))
print("vstack:")
print(np.vstack((arr6_a, arr6_b)))
print("column_stack:")
print(np.column_stack((arr6_a, arr6_b)))
